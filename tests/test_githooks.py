"""Tests for the versioned git hooks (.githooks/commit-msg, .githooks/pre-commit)."""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
HOOKS = REPO_ROOT / ".githooks"
BASH = shutil.which("bash") or "/bin/bash"

pytestmark = pytest.mark.skipif(shutil.which("bash") is None, reason="bash not available")


def run_commit_msg(tmp_path: Path, message: str) -> subprocess.CompletedProcess[str]:
    """Run the commit-msg hook on ``message`` exactly as git does (path as $1)."""
    msg_file = tmp_path / "COMMIT_EDITMSG"
    msg_file.write_text(message, encoding="utf-8")
    env = {**os.environ, "LC_ALL": "C.UTF-8"}
    return subprocess.run(  # noqa: S603 - fixed argv, test input only
        [BASH, str(HOOKS / "commit-msg"), str(msg_file)],
        capture_output=True,
        text=True,
        check=False,
        env=env,
    )


def accepted(tmp_path: Path, message: str) -> bool:
    return run_commit_msg(tmp_path, message).returncode == 0


# --------------------------------------------------------------------------- subject format


@pytest.mark.parametrize(
    "subject",
    [
        "feat(render): add donut chart export",
        "fix: handle empty csv",
        "chore(deps): bump pydantic",
        "test(sources): cover tsv delimiter",
        "perf(graph): intern node names",
        "build(tooling): pin trivy image",
        "style: ruff format",
        "refactor(core)!: split models package",
        "feat(web,ui): add compare view",
        "docs: add CLAUDE.md",
        "docs(hooks): note .claude/skills/gitnexus-cli/SKILL.md",
        "🤖 fix(sources): reject path traversal",
        "🤖 chore: scaffold",
    ],
)
def test_valid_subjects_are_accepted(tmp_path: Path, subject: str) -> None:
    assert accepted(tmp_path, subject + "\n")


@pytest.mark.parametrize(
    "subject",
    [
        "added stuff",
        "Feat: capitalised type",
        "feature(web): unknown type",
        "feat(web) missing colon",
        "feat(web):",
        "feat(web): ",
        "feat(web,): trailing comma",
        "feat(web ui): space in scope",
        "🤖feat: no space after the robot",
        "",
    ],
)
def test_invalid_subjects_are_rejected(tmp_path: Path, subject: str) -> None:
    assert not accepted(tmp_path, subject + "\n")


def test_unknown_scope_is_reported_specifically(tmp_path: Path) -> None:
    result = run_commit_msg(tmp_path, "feat(nonsense): thing\n")
    assert result.returncode == 1
    assert "Unknown scope" in result.stdout
    assert "web" in result.stdout


def test_generic_failure_lists_types_and_examples(tmp_path: Path) -> None:
    result = run_commit_msg(tmp_path, "oops\n")
    assert result.returncode == 1
    assert "INVALID COMMIT MESSAGE" in result.stdout
    assert "feat | fix" in result.stdout
    assert "🤖 fix(sources)" in result.stdout


# --------------------------------------------------------------------------- bypasses


@pytest.mark.parametrize(
    "subject",
    [
        "Merge branch 'main' into feature",
        'Revert "feat(web): add compare view"',
        "fixup! feat(web): add compare view",
        "squash! fix: handle empty csv",
        "amend! chore: scaffold",
    ],
)
def test_git_generated_and_autosquash_commits_skip_the_format_check(
    tmp_path: Path, subject: str
) -> None:
    assert accepted(tmp_path, subject + "\n")


def test_bypassed_commits_still_hit_the_banned_word_check(tmp_path: Path) -> None:
    assert not accepted(tmp_path, "Merge branch 'claude-fix'\n")
    assert not accepted(tmp_path, "fixup! feat: written by Claude\n")


# --------------------------------------------------------------------------- banned words


@pytest.mark.parametrize(
    "message",
    [
        "feat: add thing\n\nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>\n",
        "feat: add thing\n\nco-authored-by: A Human <a@example.com>\n",
        "feat: ask Claude to refactor\n",
        "feat: use anthropic sdk\n",
        "feat: switch to the sonnet model\n",
        "feat: OPUS tuning\n",
        "🤖 feat: tidy\n\nGenerated by claude code\n",
    ],
)
def test_attribution_is_banned(tmp_path: Path, message: str) -> None:
    result = run_commit_msg(tmp_path, message)
    assert result.returncode == 1
    assert "BANNED WORD" in result.stdout


@pytest.mark.parametrize(
    "message",
    [
        "docs: add CLAUDE.md\n",
        "docs: regenerate claude.md block\n",
        "chore: ignore .claude/settings.local.json\n",
        "feat: magnopus fixture\n",
        "feat: add thing\n\n# Co-Authored-By: Claude (git comment line)\n",
    ],
)
def test_allowed_mentions_pass(tmp_path: Path, message: str) -> None:
    assert accepted(tmp_path, message)


# --------------------------------------------------------------------------- length limits


def test_subject_length_limit(tmp_path: Path) -> None:
    prefix = "feat: "
    assert accepted(tmp_path, prefix + "a" * (150 - len(prefix)) + "\n")
    result = run_commit_msg(tmp_path, prefix + "a" * (151 - len(prefix)) + "\n")
    assert result.returncode == 1
    assert "TOO LONG" in result.stdout


def test_body_line_limit_excludes_blanks_comments_and_trailers(tmp_path: Path) -> None:
    ten = "\n".join(f"line {i}" for i in range(10))
    assert accepted(tmp_path, f"feat: x\n\n{ten}\n")
    extras = "\n\n# comment\nFixes: #12\nSigned-off-by: A <a@example.com>\n"
    assert accepted(tmp_path, f"feat: x\n\n{ten}{extras}")
    eleven = ten + "\nline 10"
    result = run_commit_msg(tmp_path, f"feat: x\n\n{eleven}\n")
    assert result.returncode == 1
    assert "BODY TOO LONG" in result.stdout


def test_body_width_limit_ignores_urls(tmp_path: Path) -> None:
    wide = ("word " * 40).strip()
    result = run_commit_msg(tmp_path, f"feat: x\n\n{wide}\n")
    assert result.returncode == 1
    assert "TOO WIDE" in result.stdout
    url = "https://example.com/" + "a" * 200
    assert accepted(tmp_path, f"feat: x\n\n{url}\n")


# --------------------------------------------------------------------------- wiring


def test_hooks_are_executable_and_pre_commit_runs_the_caps_check() -> None:
    for name in ("commit-msg", "pre-commit"):
        assert os.access(HOOKS / name, os.X_OK), name
    assert "scripts/check_code_caps.py" in (HOOKS / "pre-commit").read_text(encoding="utf-8")


def test_commit_msg_scopes_cover_the_package_layout() -> None:
    text = (HOOKS / "commit-msg").read_text(encoding="utf-8")
    scopes_line = next(line for line in text.splitlines() if line.startswith("SCOPES="))
    for scope in ("core", "sources", "mongo", "storage", "graph", "render", "export", "web", "ui"):
        assert scope in scopes_line
