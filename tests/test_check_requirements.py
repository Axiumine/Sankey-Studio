"""Tests for the requirements.txt check (scripts/check_requirements.py)."""

from __future__ import annotations

import shutil
import subprocess
from typing import TYPE_CHECKING

import pytest
from scripts import check_requirements as req

if TYPE_CHECKING:
    from pathlib import Path

HEADER = "# This file was autogenerated by uv via the following command:\n#    uv export\n"
PACKAGES = (
    "anyio==4.15.1 \\\n    --hash=sha256:aa\n    # via starlette\n"
    "idna==3.10 \\\n    --hash=sha256:bb\n"
)


class FakeUv:
    """A stand-in for ``subprocess.run`` that records the call and answers with a fixed result."""

    def __init__(self, stdout: str = "", stderr: str = "", code: int = 0) -> None:
        self.result = subprocess.CompletedProcess([], code, stdout, stderr)
        self.calls: list[tuple[list[str], object]] = []

    def __call__(self, argv: list[str], **kwargs: object) -> subprocess.CompletedProcess[str]:
        self.calls.append((argv, kwargs.get("cwd")))
        return self.result


@pytest.fixture(autouse=True)
def uv_on_path(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(shutil, "which", lambda _name: "/usr/bin/uv")


# --------------------------------------------------------------------------- comparison


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("", []),
        ("\n\n", []),
        ("# only a comment\n    # via x\n", []),
        ("a==1 \\  \n    --hash=sha256:aa\n", ["a==1 \\", "    --hash=sha256:aa"]),
        (
            HEADER + PACKAGES,
            ["anyio==4.15.1 \\", "    --hash=sha256:aa", "idna==3.10 \\", "    --hash=sha256:bb"],
        ),
    ],
)
def test_significant_keeps_requirement_lines_only(text: str, expected: list[str]) -> None:
    assert req.significant(text) == expected


def test_a_different_header_and_via_notes_do_not_count_as_drift() -> None:
    other = "# uv 99 wording\n" + PACKAGES.replace("# via starlette", "# via fastapi")
    assert req.drift(HEADER + PACKAGES, other) == []


def test_drift_shows_what_the_file_lacks_and_what_it_has_too_much() -> None:
    committed = "anyio==4.15.1 \\\n    --hash=sha256:aa\nold==1.0 \\\n    --hash=sha256:cc\n"
    changes = req.drift(HEADER + PACKAGES, committed)
    assert "-old==1.0 \\" in changes
    assert "+idna==3.10 \\" in changes
    assert changes[0] == "--- requirements.txt"
    assert changes[1] == "+++ uv export"


# --------------------------------------------------------------------------- uv


def test_run_export_asks_uv_for_the_locked_runtime_packages_in_the_root(tmp_path: Path) -> None:
    uv = FakeUv(stdout=PACKAGES)
    assert req.run_export(tmp_path, uv) == PACKAGES
    argv, cwd = uv.calls[0]
    assert argv[0] == "/usr/bin/uv"
    assert argv[1:] == [
        "export",
        "--locked",
        "--no-dev",
        "--no-emit-project",
        "--format",
        "requirements-txt",
    ]
    assert cwd == tmp_path


@pytest.mark.parametrize(
    ("stderr", "message"),
    [("lock is stale\n", "lock is stale"), ("", "uv exited with status 2")],
)
def test_run_export_reports_a_uv_failure(tmp_path: Path, stderr: str, message: str) -> None:
    with pytest.raises(req.ExportError, match=message):
        req.run_export(tmp_path, FakeUv(stderr=stderr, code=2))


def test_run_export_needs_uv_on_the_path(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(shutil, "which", lambda _name: None)
    with pytest.raises(req.ExportError, match="uv is not on PATH"):
        req.run_export(tmp_path, FakeUv())


# --------------------------------------------------------------------------- main


def test_main_passes_when_the_file_is_in_step(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    (tmp_path / "requirements.txt").write_text("# older header\n" + PACKAGES, encoding="utf-8")
    assert req.main([], tmp_path, FakeUv(stdout=HEADER + PACKAGES)) == 0
    assert "in step with uv.lock" in capsys.readouterr().out


def test_main_fails_with_the_fix_when_the_file_is_stale(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    (tmp_path / "requirements.txt").write_text("anyio==1.0 \\\n", encoding="utf-8")
    assert req.main([], tmp_path, FakeUv(stdout=HEADER + PACKAGES)) == 1
    err = capsys.readouterr().err
    assert "out of date with uv.lock" in err
    assert "Run `make requirements`" in err


def test_main_cuts_a_long_diff(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    many = "".join(f"pkg{i}==1.0\n" for i in range(60))
    (tmp_path / "requirements.txt").write_text("", encoding="utf-8")
    assert req.main([], tmp_path, FakeUv(stdout=many)) == 1
    assert "more lines" in capsys.readouterr().err


def test_main_fails_when_the_file_is_missing(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    assert req.main([], tmp_path, FakeUv(stdout=PACKAGES)) == 1
    assert "requirements.txt is missing" in capsys.readouterr().err


def test_main_exits_2_when_uv_fails(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert req.main([], tmp_path, FakeUv(stderr="boom", code=1)) == 2
    assert "uv export failed: boom" in capsys.readouterr().err


def test_main_write_replaces_the_file_with_the_export(tmp_path: Path) -> None:
    target = tmp_path / "requirements.txt"
    target.write_text("old\n", encoding="utf-8")
    assert req.main(["--write"], tmp_path, FakeUv(stdout=HEADER + PACKAGES)) == 0
    assert target.read_text(encoding="utf-8") == HEADER + PACKAGES
